// Whether specs and project memory are shared through git: all | memory | none.
// We manage one marked block in .gitignore and only remove lines that are plainly about the specs folder.
import { execFileSync } from "node:child_process";

export const SHARE_MODES = ["all", "memory", "none"];
const BEGIN = "# spec-driven-dev: what's shared from the specs folder (spec-driven-dev settings --share=…)";
const END = "# end spec-driven-dev";

const git = (cwd, args) => {
  try { return execFileSync("git", args, { cwd, stdio: ["ignore", "pipe", "ignore"] }).toString().trim(); } catch { return ""; }
};
const ignored = (top, rel) => !!git(top, ["check-ignore", "--no-index", rel]);

// What git does today: is the project memory ignored, and is a feature's working folder ignored?
const under = (specs, p) => (specs ? `${specs}/${p}` : p); // specs can be a whole repo (a dedicated specs repo)

export function shareState(top, specs) {
  const memory = !ignored(top, under(specs, "CONTEXT.md")) && !ignored(top, under(specs, "context/notes.md"));
  const features = !ignored(top, under(specs, "some-feature/README.md"));
  return features && memory ? "all" : memory ? "memory" : features ? "custom" : "none";
}

export function blockFor(specs, mode) {
  if (!specs) return [BEGIN, "/context/risk.md", END]; // a specs repo exists to be shared: only the generated file is ignored
  const lines = mode === "none" ? [`${specs}/`]
    : mode === "memory" ? [`${specs}/*`, `!${specs}/CONTEXT.md`, `!${specs}/context/`, `${specs}/context/risk.md`]
    : [`${specs}/context/risk.md`];
  return [BEGIN, ...lines, END];
}

// New .gitignore text for a mode, plus which existing lines would go, so the caller can ask first.
export function planShare(text, specs, mode) {
  const s = specs.replace(/^\/+|\/+$/g, "");
  const about = new Set([s, `${s}/`, `/${s}`, `/${s}/`, `${s}/*`, `/${s}/*`, `${s}/**`, `!${s}/CONTEXT.md`, `!${s}/context/`, `${s}/context/risk.md`, `/${s}/context/risk.md`,
    "# GitRisk scores, regenerated by spec-driven-dev risk"]);
  const kept = [], removed = [];
  let inBlock = false;
  for (const line of text.split("\n")) {
    if (line === BEGIN) { inBlock = true; continue; }
    if (inBlock) { if (line === END) inBlock = false; continue; }
    if (about.has(line.trim())) { if (!line.startsWith("# GitRisk") && !line.trim().endsWith("risk.md")) removed.push(line.trim()); continue; }
    kept.push(line);
  }
  while (kept.length && kept[kept.length - 1] === "") kept.pop();
  const body = kept.join("\n");
  return { text: `${body}${body ? "\n\n" : ""}${blockFor(s, mode).join("\n")}\n`, removed };
}

export const shareTitle = { all: "Share everything", memory: "Share project memory only", none: "Keep everything local", custom: "Partly shared (custom rules)" };
